/** Bounded, dependency-free validation shared by browser and trusted grader. */
export class OboValidationError extends Error {
  constructor(message, path='$') { super(`${path}: ${message}`);this.name='OboValidationError';this.path=path; }
}
export const ensure=(condition,message,path='$')=>{if(!condition)throw new OboValidationError(message,path);};
export const clone=value=>structuredClone(value);
export const byteSize=value=>new TextEncoder().encode(typeof value==='string'?value:JSON.stringify(value)).length;
const forbidden=new Set(['__proto__','prototype','constructor']);
export function parseBoundedJson(text,{bytes=1048576,depth=32}={}) {
  ensure(typeof text==='string','JSON 문자열이 필요합니다.');ensure(byteSize(text)<=bytes,'허용한 출력 크기를 넘었습니다.');
  let i=0;
  const ws=()=>{while(i<text.length&&/[\x20\t\r\n]/.test(text[i]))i++;};
  const string=()=>{
    const start=i++;let escaped=false;
    for(;i<text.length;i++) {
      const c=text[i];
      if(!escaped&&c==='"') {i++;try{return JSON.parse(text.slice(start,i));}catch{throw new OboValidationError('잘못된 문자열입니다.');}}
      if(c==='\\'&&!escaped)escaped=true;else escaped=false;
    }
    throw new OboValidationError('문자열이 끝나지 않았습니다.');
  };
  function value(level) {
    ensure(level<=depth,'JSON 중첩 한도를 넘었습니다.');ws();const c=text[i];
    if(c==='"')return string();
    if(c==='{'||c==='[') {
      i++;const object=c==='{',result=object?{}:[],keys=new Set();ws();
      if(text[i]===(object?'}':']')){i++;return result;}
      while(i<text.length) {
        let key;
        if(object){ensure(text[i]==='"','객체 키가 필요합니다.');key=string();ensure(!forbidden.has(key),'허용하지 않는 키입니다.');ensure(!keys.has(key),'중복 JSON 키입니다.');keys.add(key);ws();ensure(text[i++]===':','콜론이 필요합니다.');}
        const item=value(level+1);if(object)result[key]=item;else result.push(item);ws();
        const next=text[i++];if(next===(object?'}':']'))return result;ensure(next===',','쉼표 또는 닫는 괄호가 필요합니다.');ws();
      }
      throw new OboValidationError('JSON이 끝나지 않았습니다.');
    }
    for(const [literal,result]of [['true',true],['false',false],['null',null]])if(text.startsWith(literal,i)){i+=literal.length;return result;}
    const match=/^-?(?:0|[1-9]\d*)(?:\.\d+)?(?:[eE][+-]?\d+)?/.exec(text.slice(i));
    ensure(match,'잘못된 JSON 값입니다.');i+=match[0].length;const result=Number(match[0]);
    ensure(Number.isFinite(result)&&Math.abs(result)<=Number.MAX_SAFE_INTEGER,'수치 범위를 벗어났습니다.');return result;
  }
  const result=value(0);ws();ensure(i===text.length,'JSON 객체 뒤에 다른 출력이 있습니다.');return result;
}

/** Only the schema vocabulary generated by the OBO contract is accepted. No refs/code. */
export function checkShape(schema,value,path='$',level=0) {
  ensure(level<=32,'자료 중첩 한도를 넘었습니다.',path);
  const matches=s=>{try{checkShape(s,value,path,level+1);return true;}catch(e){if(e instanceof OboValidationError)return false;throw e;}};
  if(schema.anyOf)ensure(schema.anyOf.some(matches),'허용한 자료 형식과 다릅니다.',path);
  if(schema.oneOf)ensure(schema.oneOf.filter(matches).length===1,'하나의 자료 형식과 일치해야 합니다.',path);
  if(Object.hasOwn(schema,'const'))ensure(value===schema.const,'지원하지 않는 값입니다.',path);
  if(schema.enum)ensure(schema.enum.includes(value),'지원하지 않는 값입니다.',path);
  if(schema.type) {
    const ok=schema.type==='null'?value===null:schema.type==='array'?Array.isArray(value):schema.type==='integer'?Number.isSafeInteger(value):schema.type==='object'?value!==null&&typeof value==='object'&&!Array.isArray(value):typeof value===schema.type;
    ensure(ok,`${schema.type} 형식이 필요합니다.`,path);
  }
  if(typeof value==='number') {ensure(Number.isFinite(value),'유한한 수가 필요합니다.',path);if(schema.minimum!==undefined)ensure(value>=schema.minimum,'최솟값보다 작습니다.',path);if(schema.maximum!==undefined)ensure(value<=schema.maximum,'최댓값보다 큽니다.',path);}
  if(typeof value==='string') {
    if(schema.maxLength!==undefined)ensure([...value].length<=schema.maxLength,'문자열이 너무 깁니다.',path);
    if(schema.pattern)ensure(new RegExp(schema.pattern).test(value),'식별자 형식을 확인하세요.',path);
  }
  if(Array.isArray(value)) {
    if(schema.minItems!==undefined)ensure(value.length>=schema.minItems,'항목이 부족합니다.',path);
    if(schema.maxItems!==undefined)ensure(value.length<=schema.maxItems,'항목이 너무 많습니다.',path);
    if(schema.items)value.forEach((item,index)=>checkShape(schema.items,item,`${path}[${index}]`,level+1));
  } else if(value!==null&&typeof value==='object') {
    const keys=Object.keys(value);ensure(keys.every(k=>!forbidden.has(k)),'허용하지 않는 키입니다.',path);
    if(schema.maxProperties!==undefined)ensure(keys.length<=schema.maxProperties,'필드가 너무 많습니다.',path);
    for(const key of schema.required??[])ensure(Object.hasOwn(value,key),'필수 값이 없습니다.',`${path}.${key}`);
    for(const key of keys) {
      if(schema.propertyNames)checkShape(schema.propertyNames,key,path,level+1);
      if(schema.properties&&Object.hasOwn(schema.properties,key))checkShape(schema.properties[key],value[key],`${path}.${key}`,level+1);
      else if(schema.additionalProperties===false)throw new OboValidationError('알 수 없는 필드입니다.',`${path}.${key}`);
      else if(schema.additionalProperties&&typeof schema.additionalProperties==='object')checkShape(schema.additionalProperties,value[key],`${path}.${key}`,level+1);
    }
  }
}
export function unique(values,message='식별자가 중복되었습니다.') {ensure(new Set(values).size===values.length,message);}
export function equal(a,b) {
  if(a===b)return true;if(typeof a!==typeof b||a===null||b===null)return false;
  if(Array.isArray(a)||Array.isArray(b))return Array.isArray(a)&&Array.isArray(b)&&a.length===b.length&&a.every((v,i)=>equal(v,b[i]));
  if(typeof a==='object'){const keys=Object.keys(a);return keys.length===Object.keys(b).length&&keys.every(k=>Object.hasOwn(b,k)&&equal(a[k],b[k]));}
  return false;
}
