"""Regenerate the inline buildspec; never load orchestration from a user-supplied archive."""
from pathlib import Path


def render():
    script = Path(__file__).with_name("build_image.py").read_text(encoding="utf-8")
    command = "python3 -I - <<'DIVEON_BUILD_PY'\n" + script + "DIVEON_BUILD_PY\n"
    return ("# Generated by render_buildspec.py. Configure this as the trusted project buildspec.\n"
            "version: 0.2\nphases:\n  build:\n    commands:\n      - |\n"
            + "".join(("          " + line if line else "") + "\n" for line in command.splitlines()))


def main():
    Path(__file__).with_name("buildspec.yml").write_text(render(), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
